import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  ANOMALY_CATALOG, ANOMALY_TYPES, applyHr, applyImu, applyInjections, applyTemp, blocksFor, schedule, validateInjection,
} from "../anomalies";
import { windowIntensity } from "../engine";
import { TemperatureSeries, hashString, mulberry32 } from "../synthetic";
import type { AnomalyType } from "../types";

const fixture = JSON.parse(readFileSync(new URL("../fixtures/cross-language.json", import.meta.url), "utf8"));

describe("cross-language fixture (generated by ml/src/inject.py)", () => {
  for (const [name, c] of Object.entries<any>(fixture.anomalies)) {
    it(`matches Python for ${name}`, () => {
      const inj = { type: c.injection.type as AnomalyType, magnitude: c.injection.magnitude };
      const signal = ANOMALY_CATALOG.types[inj.type].signal;
      if (signal === "imu") {
        const got = applyImu(c.input.flat(), inj, c.offsetS);
        c.expected.flat().forEach((v: number, i: number) => expect(got[i]).toBeCloseTo(v, 12));
      } else if (signal === "hr") {
        applyHr(c.input, inj, c.offsetS).forEach((v, i) => expect(v).toBeCloseTo(c.expected[i], 12));
      } else {
        expect(applyTemp(c.input, inj, c.offsetS)).toBeCloseTo(c.expected, 12);
      }
    });
  }
  it("matches Python for the window intensity used by the activity rule", () => {
    expect(windowIntensity(fixture.intensity.window.flat(), 0)).toBeCloseTo(fixture.intensity.expectedG, 12);
  });
});

describe("catalog and validation", () => {
  it("lists the six anomaly types", () => {
    expect(ANOMALY_TYPES.sort()).toEqual(["activity_drop", "bradycardia", "fever", "hypothermia", "immobility", "tachycardia"]);
  });
  it("rejects values outside the catalog with a message in Spanish", () => {
    expect(() => validateInjection("activity_drop", 0.9, 60)).toThrow(/magnitud/);
    expect(() => validateInjection("fever", 1.5, 0)).toThrow(/duración/);
    expect(() => validateInjection("sneeze", 1, 60)).toThrow(/desconocido/);
  });
  it("covers whole blocks of 10 s", () => {
    expect(blocksFor(25)).toBe(3);
    expect(schedule("i1", "fever", 1.5, 600, 7)).toMatchObject({ startBlock: 7, endBlock: 67 });
  });
});

describe("applyInjections", () => {
  it("alters only the blocks inside the injection and reports the ground truth", () => {
    const inj = [schedule("i1", "tachycardia", 0.5, 20, 3), schedule("i2", "fever", 2, 600, 4)];
    const signals = { imu: Array(12).fill(1), hr: Array(10).fill(60), temp: 38.5 };
    expect(applyInjections(signals, inj, 2).truth).toEqual([]);
    const b4 = applyInjections(signals, inj, 4);
    expect(b4.truth.map((t) => t.type)).toEqual(["tachycardia", "fever"]);
    expect(b4.truth[0]).toMatchObject({ injectionId: "i1", offsetS: 10 });
    expect(b4.signals.hr[0]).toBeCloseTo(60 * (1 + 0.5 * (10 / 30)), 9);
    expect(b4.signals.temp).toBeCloseTo(38.5, 9); // ramp starts at 0
    expect(applyInjections(signals, inj, 5).truth.map((t) => t.type)).toEqual(["fever"]);
  });
});

describe("synthetic temperature", () => {
  it("is reproducible per dog and seed, and stays near the dog's mean", () => {
    const a = new TemperatureSeries("toby", 1), b = new TemperatureSeries("toby", 1), c = new TemperatureSeries("luna", 1);
    const va = Array.from({ length: 2000 }, () => a.next());
    expect(Array.from({ length: 2000 }, () => b.next())).toEqual(va);
    expect(c.mean).not.toBe(a.mean);
    expect(a.mean).toBeGreaterThanOrEqual(38.1);
    expect(a.mean).toBeLessThanOrEqual(39.1);
    const avg = va.reduce((s, v) => s + v, 0) / va.length;
    expect(Math.abs(avg - a.mean)).toBeLessThan(0.15);
    expect(va.every((v) => v > 37.7 && v < 39.5)).toBe(true);
  });
  it("hash and PRNG are deterministic", () => {
    expect(hashString("toby")).toBe(hashString("toby"));
    const r1 = mulberry32(42), r2 = mulberry32(42);
    expect([r1(), r1(), r1()]).toEqual([r2(), r2(), r2()]);
  });
});
